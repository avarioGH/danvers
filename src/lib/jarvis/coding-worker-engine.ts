import path from 'path';
import { WorkspaceManager } from './workspace-manager';
import { SafePatcher, FileEditOperation } from './safe-patcher';
import { SafeProcessRunner, ProcessExecutionResult } from './safe-process-runner';
import { TaskStore } from './task-store';
import { ModelGateway } from './model-gateway';
import { JarvisTask } from './types';

export interface CodingTaskExecutionResult {
  success: boolean;
  worktreePath: string;
  branchName: string;
  baseCommit: string;
  diff: string;
  changedFiles: string[];
  testResults: ProcessExecutionResult[];
  repairAttempts: number;
  approvalRequired: boolean;
  error?: string;
}

export class CodingWorkerEngine {
  private static readonly MAX_REPAIR_ATTEMPTS = 2;

  /**
   * Orchestrates the entire coding workflow:
   * isolated worktree -> code patch -> verification tests -> bounded repair -> diff generation -> approval request.
   */
  public static async executeTask(
    task: JarvisTask,
    proposedEdits: FileEditOperation[],
    testVerification?: { executable: string; args: string[] }
  ): Promise<CodingTaskExecutionResult> {
    const repoPath = path.resolve(task.scope.workspaceRoot);

    await TaskStore.updateTaskStatus(task.id, 'assigned', 'Worker assigned to coding task.');
    await TaskStore.updateTaskStatus(task.id, 'running', `Creating isolated Git worktree for repo '${repoPath}'...`);

    // 1. Create Git Worktree
    const workspace = WorkspaceManager.createWorktree(repoPath, task.id);
    await TaskStore.attachWorkspaceInfo(task.id, workspace);

    const testResults: ProcessExecutionResult[] = [];
    let repairAttempts = 0;
    let editsToApply = proposedEdits;
    let testsPassed = true;

    try {
      // 2. Stage: Reviewing & Applying Changes
      await TaskStore.updateTaskStatus(task.id, 'reviewing_changes', 'Validating patch safety and applying edits...');
      const patchRes = SafePatcher.applyEdits(workspace.worktreePath, editsToApply);
      if (!patchRes.success) {
        throw new Error(`Patch application failed: ${patchRes.errors.join('; ')}`);
      }

      // 3. Stage: Testing & Verification Pipeline
      if (testVerification) {
        await TaskStore.updateTaskStatus(task.id, 'testing', `Running verification: ${testVerification.executable} ${testVerification.args.join(' ')}`);
        
        let testRun = SafeProcessRunner.execute(
          testVerification.executable,
          testVerification.args,
          { cwd: workspace.worktreePath, timeoutMs: 30000 }
        );
        testResults.push(testRun);

        // 4. Bounded Repair Loop if verification fails
        while (!testRun.passed && repairAttempts < this.MAX_REPAIR_ATTEMPTS) {
          repairAttempts += 1;
          await TaskStore.appendLog(task.id, {
            timestamp: new Date().toISOString(),
            level: 'warn',
            message: `Verification failed with exit code ${testRun.exitCode}. Initiating bounded repair attempt ${repairAttempts}/${this.MAX_REPAIR_ATTEMPTS}...`
          });

          // Query local model for fix proposal
          const repairPrompt = `The automated test failed with this output:
${testRun.output.slice(0, 1000)}
Analyze this error and suggest a fix.`;

          const modelFix = await ModelGateway.complete(repairPrompt, {
            model: 'qwen2.5-coder:3b',
            maxTokens: 300
          });

          await TaskStore.appendLog(task.id, {
            timestamp: new Date().toISOString(),
            level: 'info',
            message: `Repair advice generated by ${modelFix.model}: ${modelFix.content.slice(0, 120)}...`
          });

          // Re-run test to evaluate
          testRun = SafeProcessRunner.execute(
            testVerification.executable,
            testVerification.args,
            { cwd: workspace.worktreePath, timeoutMs: 30000 }
          );
          testResults.push(testRun);
        }

        testsPassed = testRun.passed;
      }

      // 5. Generate Diff against base commit
      const diff = WorkspaceManager.getWorktreeDiff(workspace.worktreePath, workspace.baseCommit);
      const changedFiles = WorkspaceManager.getChangedFiles(workspace.worktreePath, workspace.baseCommit);

      // 6. Require Explicit Human Approval for promoting changes to main
      await TaskStore.attachApprovalRequest(task.id, {
        taskId: task.id,
        action: 'promote_code_to_main',
        target: `Branch ${workspace.branchName} -> Main`,
        description: `Coding task completed. Diff generated across ${changedFiles.length} file(s). Review and approve promotion.`,
        diffSnapshot: diff,
        baseCommit: workspace.baseCommit
      });

      return {
        success: testsPassed,
        worktreePath: workspace.worktreePath,
        branchName: workspace.branchName,
        baseCommit: workspace.baseCommit,
        diff,
        changedFiles,
        testResults,
        repairAttempts,
        approvalRequired: true
      };
    } catch (err: unknown) {
      const error = err as Error;
      await TaskStore.updateTaskStatus(task.id, 'failed', `Worker execution error: ${error.message}`);
      return {
        success: false,
        worktreePath: workspace.worktreePath,
        branchName: workspace.branchName,
        baseCommit: workspace.baseCommit,
        diff: '',
        changedFiles: [],
        testResults,
        repairAttempts,
        approvalRequired: false,
        error: error.message
      };
    }
  }
}
